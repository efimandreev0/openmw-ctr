# -*- coding: utf-8 -*-
"""ETC1 texture preprocessor for the 3DS port. RUN FROM WSL (needs devkitPro
tex3ds and Pillow: `python3 preprocess_textures_etc1.py "/mnt/c/.../Data Files"`).

For every opaque DXT textures/*.dds (BSA or loose), produces a PICA-native
.ctex next to it: 12-byte header + raw 3DS-tiled ETC1 payload, generated by
tex3ds. The game's ImageManager prefers .ctex over .dds: PICA samples ETC1
natively, so uploads become a straight memcpy (no CPU DXT decode) and linear
memory use drops ~4x versus RGBA8-decoded DXT.

Alpha textures (foliage, grilles) are skipped in this pass — they keep the
DXT-decode path. Non-power-of-two sources are skipped too.

.ctex layout (little-endian): u32 magic 'CTX1', u16 width, u16 height,
u32 payloadSize, then payload (tex3ds t3x body with its 21-byte header cut:
the last width*height/2 bytes of the t3x are the raw tiled ETC1 data).
"""
import io
import os
import struct
import subprocess
import sys
import tempfile

from PIL import Image

TEX3DS = "/opt/devkitpro/tools/bin/tex3ds"

SKIP_PREFIXES = (
    "textures/menu_",
    "textures/tx_menubook",
    "textures/bookart/",
    "textures/fonts/",
    "textures/splash/",
    "textures/cursor",
    "textures/omw_",
)

# Downscale while the larger side exceeds this (matches downscale_textures.py).
TARGET_MAX_SIDE = 128
MIN_SIDE = 8


def read_bsa_index(path):
    with open(path, "rb") as f:
        head = f.read(12)
        if len(head) < 12:
            return {}
        version, hash_off, count = struct.unpack("<III", head)
        if version != 0x100:
            return {}
        sizes_offsets = struct.unpack("<%dI" % (count * 2), f.read(count * 8))
        name_offs = struct.unpack("<%dI" % count, f.read(count * 4))
        names_blob = f.read(hash_off - (count * 8 + count * 4))
        data_base = 12 + hash_off + count * 8
        out = {}
        for i in range(count):
            end = names_blob.index(b"\x00", name_offs[i])
            name = names_blob[name_offs[i]:end].decode("cp1251", "replace").lower().replace("\\", "/")
            out[name] = (data_base + sizes_offsets[i * 2 + 1], sizes_offsets[i * 2])
        return out


def is_pot(v):
    return v > 0 and (v & (v - 1)) == 0


def convert_one(blob, out_path, tmpdir):
    """Return (ok, reason)."""
    try:
        im = Image.open(io.BytesIO(blob))
        im.load()
    except Exception as e:
        return False, "decode: %s" % e
    if im.mode == "RGBA":
        try:
            lo, hi = im.getchannel("A").getextrema()
        except Exception:
            lo, hi = 255, 255
        if lo < 250:
            return False, "alpha"
    w, h = im.size
    if not (is_pot(w) and is_pot(h)):
        return False, "npot"
    while max(w, h) > TARGET_MAX_SIDE and min(w, h) // 2 >= MIN_SIDE:
        w //= 2
        h //= 2
    if (w, h) != im.size:
        im = im.resize((w, h), Image.LANCZOS)
    png = os.path.join(tmpdir, "in.png")
    t3x = os.path.join(tmpdir, "out.t3x")
    im.convert("RGB").save(png)
    r = subprocess.run([TEX3DS, "-f", "etc1", "-z", "none", "-o", t3x, png],
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if r.returncode != 0:
        return False, "tex3ds"
    data = open(t3x, "rb").read()
    payload_size = w * h // 2  # ETC1 = 4bpp
    if len(data) < payload_size:
        return False, "t3x size"
    payload = data[-payload_size:]
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "wb") as f:
        f.write(struct.pack("<IHHI", 0x31585443, w, h, payload_size))  # 'CTX1'
        f.write(payload)
    return True, ""


def main():
    if len(sys.argv) < 2:
        print(__doc__)
        return 1
    data_dir = sys.argv[1]
    if not os.path.isfile(TEX3DS):
        print("tex3ds not found at", TEX3DS)
        return 1

    merged = {}
    order = ["morrowind.bsa", "tribunal.bsa", "bloodmoon.bsa"]
    bsas = [f for f in os.listdir(data_dir) if f.lower().endswith(".bsa")]
    bsas.sort(key=lambda n: (order.index(n.lower()) if n.lower() in order else 99, n.lower()))
    for bsa in bsas:
        for name, loc in read_bsa_index(os.path.join(data_dir, bsa)).items():
            if name.startswith("textures/") and name.endswith(".dds"):
                merged[name] = ("bsa", os.path.join(data_dir, bsa), loc)
    # Loose files win over BSA (and are already downscaled).
    tex_root = os.path.join(data_dir, "textures")
    for root, _, files in os.walk(tex_root):
        for fn in files:
            if fn.lower().endswith(".dds"):
                full = os.path.join(root, fn)
                rel = os.path.relpath(full, data_dir).replace("\\", "/").lower()
                merged[rel] = ("loose", full, None)

    done = skipped = 0
    reasons = {}
    with tempfile.TemporaryDirectory() as tmpdir:
        for name, (kind, src, loc) in sorted(merged.items()):
            if any(name.startswith(p) for p in SKIP_PREFIXES):
                skipped += 1
                continue
            if kind == "bsa":
                with open(src, "rb") as f:
                    f.seek(loc[0])
                    blob = f.read(loc[1])
            else:
                blob = open(src, "rb").read()
            out_path = os.path.join(data_dir, *(name[:-4] + ".ctex").split("/"))
            ok, why = convert_one(blob, out_path, tmpdir)
            if ok:
                done += 1
                if done % 250 == 0:
                    print("...", done)
            else:
                skipped += 1
                reasons[why.split(":")[0]] = reasons.get(why.split(":")[0], 0) + 1
    print("converted: %d | skipped: %d | reasons: %s" % (done, skipped, reasons))
    print("NOTE: delete config/vfs_dir_*.bin so the VFS rescans the new files.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
